# Core Adapter Pipeline
# ---------------------------------------------------------------------------


class OrderAiAdapter:
    """Pre-Resolver translation layer conforming strictly to v1.3 §5.1."""

    def __init__(self, extractor: Optional[RunPodExtractor] = None):
        self.extractor = extractor or RunPodExtractor()
        self.h1_lexicon = load_h1_lexicon()
        self.h5_lexicon = _load_h5_lexicon()

    async def adapt(
        self,
        masked_text: str,
        catalog: Dict[str, Sequence[str]],
    ) -> AdapterOutput:
        """Execute full extraction, coordinate projection, H1 double-check, and H5 detection.

        Args:
            masked_text: PII-redacted order text.
            catalog: Explicitly injected tenant catalog (mandatory).

        Returns:
            AdapterOutput with lines, conditions, and ai_mode.

        Raises:
            ValueError: If catalog is None or text exceeds 4000 code points.
            AiAndFallbackUnavailableError: If both LLM and Fallback are unavailable.
        """
        # Rule 2: Explicit catalog injection is mandatory
        if catalog is None:
            raise ValueError(
                "Tenant catalog must be explicitly provided to Adapter (no silent fallback)."
            )

        # 4000 code point limit defense (Gate 0 contract)
        if len(masked_text) > 4000:
            raise MessageTooLongError(
                f"Masked text length {len(masked_text)} exceeds 4000 code points limit"
            )

        # 1. Run LLM or Fallback extractor
        resp: ExtractorResponse = await self.extractor.extract(masked_text, catalog=catalog)

        raw_rows = resp.result.rows
        consumed_spans: List[Tuple[int, int]] = []
        adapter_lines: List[AdapterLine] = []

        # 2. Process each row with H1 double-check and coordinate projection
        for idx, row in enumerate(raw_rows):
            line_id = f"LINE_{idx}"
            span = row.span

            # Coordinate projection
            s_start, s_end, is_exact, loc_issue = locate_span(masked_text, span, consumed_spans)

            # Fault isolation: if span cannot be located
            if loc_issue == "SOURCE_EVIDENCE_INVALID":
                adapter_lines.append(
                    AdapterLine(
                        line_id=line_id,
                        span=span,
                        span_start=0,
                        span_end=0,
                        family_id="UNKNOWN",
                        qty=None,
                        uom=None,
                        pack_size=None,
                        field_evidence=[],
                        match_source="RAPIDFUZZ_FALLBACK",
                        issue_code="LOW_CONFIDENCE_MATCH",
                        reason_code="SOURCE_EVIDENCE_INVALID",
                    )
                )
                continue

            raw_span = (
                masked_text[s_start:s_end]
                if (s_start < s_end and s_end <= len(masked_text))
                else span
            )

            if loc_issue == "OVERLAPPING_SPAN":
                # Check if this row is a DUPLICATE_SPAN (exact same interval and identical fields/evidence)
                matching_prev = next(
                    (
                        candidate
                        for candidate in adapter_lines
                        if candidate.span_start == s_start and candidate.span_end == s_end
                    ),
                    None,
                )
                if matching_prev is not None:
                    det_qty, _, _, _ = parse_quantity_h1(raw_span, lexicon=self.h1_lexicon)
                    uom = parse_uom_h1(raw_span, lexicon=self.h1_lexicon)
                    pack_size = parse_pack_size_h1(raw_span, lexicon=self.h1_lexicon)
                    fam_cand = row.fam if row.fam in catalog else "UNKNOWN"
                    if (
                        fam_cand == matching_prev.family_id
                        and det_qty == matching_prev.qty
                        and uom == matching_prev.uom
                        and pack_size == matching_prev.pack_size
                    ):
                        logger.info(
                            "DUPLICATE_SPAN: deduplicating identical row at [%d:%d]", s_start, s_end
                        )
                        continue
                    # Different evidence -> retain as separate line (do not add to consumed_spans)
                else:
                    # Overlapping interval -> mark as LOW_CONFIDENCE_MATCH with OVERLAPPING_SPAN
                    adapter_lines.append(
                        AdapterLine(
                            line_id=line_id,
                            span=raw_span,
                            span_start=s_start,
                            span_end=s_end,
                            family_id="UNKNOWN",
                            qty=None,
                            uom=None,
                            pack_size=None,
                            field_evidence=[],
                            match_source="LLM_EXTRACTED"
                            if resp.ai_mode == "LLM"
                            else "RAPIDFUZZ_FALLBACK",
                            issue_code="LOW_CONFIDENCE_MATCH",
                            reason_code="OVERLAPPING_SPAN",
                        )
                    )
                    continue
            else:
                consumed_spans.append((s_start, s_end))

            # H1 Double-check: LLM quantity is only a candidate
            # Parse deterministic quantity, uom, and pack_size on the verbatim raw_span
            norm_span, span_map = normalize_text_with_map(raw_span)
            det_qty, det_reason, q_start, q_end = parse_quantity_h1(
                raw_span, lexicon=self.h1_lexicon
            )
            uom, u_start, u_end = parse_uom_h1_with_offsets(raw_span, lexicon=self.h1_lexicon)
            pack_size, p_start, p_end = parse_pack_size_h1_with_offsets(
                raw_span, lexicon=self.h1_lexicon
            )

            final_qty: Optional[int] = None
            issue_code: Optional[str] = None
            reason_code: Optional[str] = None
            model_coerced = False
            field_evidences: List[FieldEvidence] = []

            # 1) Quantity verification
            if det_reason in ("INVALID_QUANTITY", "AMBIGUOUS_QUANTITY"):
                final_qty = None
                issue_code = "LOW_CONFIDENCE_MATCH"
                reason_code = det_reason
            elif det_qty is not None:
                if row.qty is not None:
                    model_int: Optional[int] = None
                    if isinstance(row.qty, str) and row.qty.isascii() and row.qty.isdigit():
                        model_int = int(row.qty)
                        model_coerced = True
                        logger.info(
                            "MODEL_TYPE_COERCED: string quantity coerced to int at span [%d:%d]",
                            s_start,
                            s_end,
                        )
                    elif isinstance(row.qty, int) and not isinstance(row.qty, bool):
                        model_int = row.qty

                    if model_int == det_qty:
                        final_qty = det_qty
                    else:
                        final_qty = None
                        issue_code = "LOW_CONFIDENCE_MATCH"
                        reason_code = "FIELD_NOT_EVIDENCED"
                else:
                    final_qty = det_qty

                if (
                    final_qty is not None
                    and q_start is not None
                    and q_end is not None
                    and len(span_map) >= q_end
                ):
                    q_ev_start = s_start + span_map[q_start]
                    q_ev_end = s_start + span_map[q_end - 1] + 1
                    field_evidences.append(
                        FieldEvidence(
                            field="qty",
                            raw_text=masked_text[q_ev_start:q_ev_end],
                            start=q_ev_start,
                            end=q_ev_end,
                        )
                    )
            else:
                final_qty = None
                issue_code = "LOW_CONFIDENCE_MATCH"
                reason_code = "FIELD_NOT_EVIDENCED"

            # 2) UOM verification
            if uom is not None:
                if u_start is not None and u_end is not None and len(span_map) >= u_end:
                    u_ev_start = s_start + span_map[u_start]
                    u_ev_end = s_start + span_map[u_end - 1] + 1
                    field_evidences.append(
                        FieldEvidence(
                            field="uom",
                            raw_text=masked_text[u_ev_start:u_ev_end],
                            start=u_ev_start,
                            end=u_ev_end,
                        )
                    )
                else:
                    uom = None
                    issue_code = "LOW_CONFIDENCE_MATCH"
                    if not reason_code:
                        reason_code = "FIELD_NOT_EVIDENCED"
            elif row.uom:
                issue_code = "LOW_CONFIDENCE_MATCH"
                if not reason_code:
                    reason_code = "FIELD_NOT_EVIDENCED"

            # 3) Pack Size verification
            if pack_size is not None:
                if p_start is not None and p_end is not None and len(span_map) >= p_end:
                    p_ev_start = s_start + span_map[p_start]
                    p_ev_end = s_start + span_map[p_end - 1] + 1
                    field_evidences.append(
                        FieldEvidence(
                            field="pack_size",
                            raw_text=masked_text[p_ev_start:p_ev_end],
                            start=p_ev_start,
                            end=p_ev_end,
                        )
                    )
                else:
                    pack_size = None
                    issue_code = "LOW_CONFIDENCE_MATCH"
                    if not reason_code:
                        reason_code = "FIELD_NOT_EVIDENCED"
            elif row.pack_size:
                issue_code = "LOW_CONFIDENCE_MATCH"
                if not reason_code:
                    reason_code = "FIELD_NOT_EVIDENCED"

            # 4) Family validation
            fam_id = row.fam
            if not fam_id or fam_id not in catalog:
                fam_id = "UNKNOWN"
                issue_code = "LOW_CONFIDENCE_MATCH"
                if not reason_code:
                    reason_code = (
                        "UNKNOWN_PRODUCT"
                        if (fam_id and fam_id != "UNKNOWN")
                        else "FAMILY_NOT_EVIDENCED"
                    )
            else:
                fam_phrases = [normalize_text(p) for p in catalog.get(fam_id, [])]
                text_to_search = normalize_text(masked_text)
                if not any(p in text_to_search for p in fam_phrases):
                    fam_id = "UNKNOWN"
                    issue_code = "LOW_CONFIDENCE_MATCH"
                    if not reason_code:
                        reason_code = "FAMILY_NOT_EVIDENCED"

            match_source = "LLM_EXTRACTED" if resp.ai_mode == "LLM" else "RAPIDFUZZ_FALLBACK"

            adapter_lines.append(
                AdapterLine(
                    line_id=line_id,
                    span=raw_span,
                    span_start=s_start,
                    span_end=s_end,
                    family_id=fam_id,
                    qty=final_qty,
                    uom=uom,
                    pack_size=pack_size,
                    field_evidence=field_evidences,
                    match_source=match_source,
                    issue_code=issue_code,
                    reason_code=reason_code,
                    model_coerced=model_coerced,
                )
            )

        # 3. Independent H5 condition extraction
        conditions = extract_conditions_h5(
            masked_text,
            lexicon=self.h5_lexicon,
            total_lines=len(adapter_lines),
        )

        # 4. Resolve global ai_mode
        llm_line_count = sum(1 for line in adapter_lines if line.match_source == "LLM_EXTRACTED")
        fallback_line_count = sum(
            1 for line in adapter_lines if line.match_source == "RAPIDFUZZ_FALLBACK"
        )

        if resp.ai_mode == "FALLBACK":
            final_mode = "FALLBACK"
        elif llm_line_count > 0 and fallback_line_count > 0:
            final_mode = "MIXED"
        elif llm_line_count > 0:
            final_mode = "LLM"
        elif fallback_line_count > 0:
            final_mode = "FALLBACK"
        else:
            final_mode = resp.ai_mode

        return AdapterOutput(
            lines=adapter_lines,
            conditions=conditions,
            ai_mode=final_mode,
            ignored_spans=resp.result.ignored_spans,
        )
