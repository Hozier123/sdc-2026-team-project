"""KiraOrder AI Adapter (Pre-Resolver Subsystem).

Complies strictly with Gate 0 v4 contract and Review Revision v2:
- Mandatory explicit catalog injection (raises ValueError if catalog is None)
- Span location using Unicode code points and index_map (resilient to normalization length changes)
- Strict H1 double-check: LLM qty is only a candidate; deterministic pipeline always takes precedence
- H5 independent condition engine: 16 truth-table parity, price_basis='UNIT' on _UNIT_PRICE match, decimal string amounts
- Zero domain decision: outputs pre-resolver AdapterOutput without draft_id, blocking, target_line_ids
"""

import json
import logging
import re
from dataclasses import dataclass, field
from typing import Any, Dict, Final, List, Optional, Sequence, Tuple

from app.ai.extractor import (
    ExtractorResponse,
    MessageTooLongError,
    RunPodExtractor,
)
from app.ai.fallback import (
    _find_lexicon_path,
    load_h1_lexicon,
    normalize_text,
    normalize_text_with_map,
    parse_pack_size_h1,
    parse_pack_size_h1_with_offsets,
    parse_quantity_h1,
    parse_uom_h1,
    parse_uom_h1_with_offsets,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# H5 Reference Patterns from contract_oracles.py:240-248
# (Gate 0 v4 oracle implementation details; not in condition-triggers-v3.json)
# ---------------------------------------------------------------------------
_AMOUNT_VALUE = re.compile(r"\brm\s*(\d+(?:\.\d{1,2})?)\b", re.IGNORECASE)
_ALLOCATION = re.compile(
    r"\brm\s*\d+(?:\.\d{1,2})?\s+for\s+[1-9]\d*\s+(?:ctn|cartons?|packs?|bags?|pcs?)\b",
    re.IGNORECASE,
)
_UNIT_PRICE = re.compile(
    r"\brm\s*\d+(?:\.\d{1,2})?\s+(?:untuk\s+1|per)\s+(?:ctn|cartons?|packs?|bags?|pcs?|kg)\b",
    re.IGNORECASE,
)
_AMOUNT_WITH_CONTEXT_TOKENS: Final[Tuple[str, ...]] = ("kalau", "if ", "?", "？")


@dataclass(frozen=True)
class FieldEvidence:
    """Deterministic field evidence anchored to masked_text Unicode code points."""

    field: str
    raw_text: str
    start: int  # Unicode code point in masked_text
    end: int  # Unicode code point in masked_text
    normalizer_version: str = "field-evidence-v2"


@dataclass(frozen=True)
class AdapterLine:
    """Pre-Resolver product line candidate generated by Adapter."""

    line_id: str
    span: str
    span_start: int
    span_end: int
    family_id: str
    qty: Optional[int]
    uom: Optional[str]
    pack_size: Optional[str]
    field_evidence: List[FieldEvidence]
    match_source: str  # "LLM_EXTRACTED" | "RAPIDFUZZ_FALLBACK" | "SUGGESTED_DEFAULT"
    issue_code: Optional[str] = None
    reason_code: Optional[str] = None
    model_coerced: bool = False


@dataclass(frozen=True)
class ExtractedCondition:
    """Pre-Resolver condition candidate extracted independently via H5 rules."""

    kind: str  # "STOCK" | "PRICE" | "TIME" | "OTHER"
    span: str  # verbatim matched condition phrase
    span_start: int  # Unicode code point in masked_text
    span_end: int  # Unicode code point in masked_text
    condition_scope: str  # "SINGLE_LINE" | "MULTI_LINE" | "UNKNOWN"
    price_basis: Optional[str]  # "UNIT" | "TOTAL" | "UNKNOWN" (only for PRICE)
    requested_amount: Optional[str] = None  # decimal string e.g. "95", "12.50" (never float)


@dataclass(frozen=True)
class AdapterOutput:
    """Clean, verified pre-resolver data contract delivered to parse-draft."""

    lines: List[AdapterLine]
    conditions: List[ExtractedCondition]
    ai_mode: str  # "LLM" | "FALLBACK" | "ALIAS_ONLY" | "MIXED"
    ignored_spans: List[str] = field(default_factory=list)


def _load_h5_lexicon() -> Dict[str, Any]:
    """Dynamically load condition-triggers-v3.json."""
    h1_path = _find_lexicon_path()
    h5_path = h1_path.parent / "condition-triggers-v3.json"
    if not h5_path.is_file():
        raise FileNotFoundError(f"Gate 0 condition-triggers-v3.json not found at {h5_path}")
    return json.loads(h5_path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# Coordinate Projection & Span Locating
# ---------------------------------------------------------------------------


def locate_span(
    masked_text: str,
    span: str,
    consumed_spans: List[Tuple[int, int]],
) -> Tuple[int, int, bool, Optional[str]]:
    """Locate verbatim or normalized span in masked_text without overlapping consumed spans.

    Returns:
        (start, end, is_exact, issue_reason)
    """
    if not span:
        return 0, 0, False, "SOURCE_EVIDENCE_INVALID"

    # 1. Direct substring search
    first_overlapping: Optional[Tuple[int, int]] = None
    start_pos = 0
    while True:
        idx = masked_text.find(span, start_pos)
        if idx == -1:
            break
        end_idx = idx + len(span)
        # Check non-overlapping constraint
        overlap = any(max(idx, c_s) < min(end_idx, c_e) for c_s, c_e in consumed_spans)
        if not overlap:
            return idx, end_idx, True, None
        if first_overlapping is None:
            first_overlapping = (idx, end_idx)
        start_pos = idx + 1

    # 2. Normalized space search with index_map
    norm_text, text_map = normalize_text_with_map(masked_text)
    norm_span = normalize_text(span)
    if not norm_span:
        return 0, 0, False, "SOURCE_EVIDENCE_INVALID"

    norm_start_pos = 0
    while True:
        norm_idx = norm_text.find(norm_span, norm_start_pos)
        if norm_idx == -1:
            break
        if text_map and norm_idx + len(norm_span) <= len(text_map):
            norm_end = norm_idx + len(norm_span)
            orig_start = text_map[norm_idx]
            orig_end = text_map[norm_end - 1] + 1
            overlap = any(max(orig_start, c_s) < min(orig_end, c_e) for c_s, c_e in consumed_spans)
            if not overlap:
                return orig_start, orig_end, False, None
            if first_overlapping is None:
                first_overlapping = (orig_start, orig_end)
        norm_start_pos = norm_idx + 1

    if first_overlapping is not None:
        return first_overlapping[0], first_overlapping[1], False, "OVERLAPPING_SPAN"

    return 0, 0, False, "SOURCE_EVIDENCE_INVALID"


# ---------------------------------------------------------------------------
# H5 Independent Condition Engine
# ---------------------------------------------------------------------------


def _context_ok(value: str, trigger: Dict[str, Any], lexicon: Dict[str, Any]) -> bool:
    """Validate contextual triggers matching contract_oracles.py:255-262."""
    if not trigger.get("requires_context"):
        return True
    negatives = [normalize_text(n) for n in lexicon.get("negative_contexts", []) if "<" not in n]
    if any(token in value for token in negatives):
        return False
    markers = [normalize_text(m) for m in lexicon.get("context_markers", [])]
    return any(token in value for token in markers)


def extract_conditions_h5(
    masked_text: str,
    lexicon: Optional[Dict[str, Any]] = None,
    total_lines: int = 1,
) -> List[ExtractedCondition]:
    """Execute H5 condition detection independently from LLM output.

    Guarantees 16 truth-table parity and accurately projects start/end offsets.
    """
    if lexicon is None:
        lexicon = _load_h5_lexicon()

    norm_text, text_map = normalize_text_with_map(masked_text)
    conditions: List[ExtractedCondition] = []

    # Note: condition_scope is SINGLE_LINE if total_lines == 1 else UNKNOWN (P0 simplification)
    scope = "SINGLE_LINE" if total_lines == 1 else "UNKNOWN"

    # 1. Check STOCK triggers
    stock_cond: Optional[ExtractedCondition] = None
    for tr in lexicon.get("triggers", []):
        if tr["kind"] == "STOCK" and re.search(tr["pattern"], norm_text, re.IGNORECASE):
            m = re.search(tr["pattern"], norm_text, re.IGNORECASE)
            if m:
                norm_s, norm_e = m.start(), m.end()
                orig_s = text_map[norm_s] if text_map else norm_s
                orig_e = text_map[norm_e - 1] + 1 if (text_map and norm_e > 0) else norm_e
                stock_cond = ExtractedCondition(
                    kind="STOCK",
                    span=masked_text[orig_s:orig_e],
                    span_start=orig_s,
                    span_end=orig_e,
                    condition_scope=scope,
                    price_basis=None,
                    requested_amount=None,
                )
                break

    # 2. Check PRICE triggers & amounts
    explicit_price = False
    price_span_offsets: Optional[Tuple[int, int]] = None
    for tr in lexicon.get("triggers", []):
        if tr["kind"] != "PRICE":
            continue
        if tr.get("requires_context") and not _context_ok(norm_text, tr, lexicon):
            continue
        m = re.search(tr["pattern"], norm_text, re.IGNORECASE)
        if m:
            explicit_price = True
            price_span_offsets = (m.start(), m.end())
            break

    amount_match = _AMOUNT_VALUE.search(norm_text)
    amount_with_context = bool(amount_match) and any(
        token in norm_text for token in ("kalau", "if ", "?", "？")
    )
    alloc_match = _ALLOCATION.search(norm_text)
    allocation = bool(alloc_match)

    price_cond: Optional[ExtractedCondition] = None
    if explicit_price or amount_with_context or allocation:
        if price_span_offsets is not None:
            p_norm_s, p_norm_e = price_span_offsets
        elif allocation and alloc_match:
            p_norm_s, p_norm_e = alloc_match.start(), alloc_match.end()
        elif amount_match:
            p_norm_s, p_norm_e = amount_match.start(), amount_match.end()
        else:
            p_norm_s, p_norm_e = 0, len(norm_text)

        orig_s = text_map[p_norm_s] if text_map else p_norm_s
        orig_e = text_map[p_norm_e - 1] + 1 if (text_map and p_norm_e > 0) else p_norm_e

        price_basis = "UNIT" if _UNIT_PRICE.search(norm_text) else "UNKNOWN"

        req_amount: Optional[str] = None
        span_amt_match = _AMOUNT_VALUE.search(norm_text[p_norm_s:p_norm_e])
        if span_amt_match:
            req_amount = span_amt_match.group(1)

        price_cond = ExtractedCondition(
            kind="PRICE",
            span=masked_text[orig_s:orig_e],
            span_start=orig_s,
            span_end=orig_e,
            condition_scope=scope,
            price_basis=price_basis,
            requested_amount=req_amount,
        )

    # 3. Check TIME_OR_OTHER triggers (mapped to OTHER per Gate 0 OpenAPI schema)
    other_cond: Optional[ExtractedCondition] = None
    for tr in lexicon.get("triggers", []):
        if tr["kind"] == "TIME_OR_OTHER" and re.search(tr["pattern"], norm_text, re.IGNORECASE):
            m = re.search(tr["pattern"], norm_text, re.IGNORECASE)
            if m:
                norm_s, norm_e = m.start(), m.end()
                orig_s = text_map[norm_s] if text_map else norm_s
                orig_e = text_map[norm_e - 1] + 1 if (text_map and norm_e > 0) else norm_e
                other_cond = ExtractedCondition(
                    kind="OTHER",
                    span=masked_text[orig_s:orig_e],
                    span_start=orig_s,
                    span_end=orig_e,
                    condition_scope=scope,
                    price_basis=None,
                    requested_amount=None,
                )
                break

    if stock_cond:
        conditions.append(stock_cond)
    if price_cond:
        conditions.append(price_cond)
    if other_cond:
        conditions.append(other_cond)

    return conditions


